create table if not exists public.lojas (
  id bigint generated always as identity primary key,
  nome text not null,
  endereco text,
  cor_destaque text default '#3ecf6e'::text,
  created_at timestamptz default now(),
  cidade text,
  cnpj text,
  tel text,
  logo text,
  ativa boolean not null default true,
  cobranca_para text not null default 'loja'::text
    check (cobranca_para = any (array['loja'::text,'dono'::text])),
  ordem integer not null default 0
);

create table if not exists public.perfis (
  id uuid primary key references auth.users(id),
  nome text not null,
  email text not null,
  role text not null default 'owner'::text,
  loja_id bigint references public.lojas(id),
  is_admin boolean default false,
  created_at timestamptz default now(),
  cpf text,
  ordem integer not null default 0
);

create table if not exists public.loja_membros (
  id bigint generated always as identity primary key,
  user_id uuid not null references auth.users(id),
  loja_id bigint not null references public.lojas(id),
