-- lojas
drop policy if exists "insert_nova_loja" on public.lojas;
create policy "insert_nova_loja" on public.lojas
for insert to authenticated
with check (
  sou_admin()
  or (
    (select count(*) from loja_membros lm
     where lm.user_id = auth.uid()
       and lm.role = 'owner'
       and lm.created_at > (now() - interval '24:00:00')) < 5
  )
);

drop policy if exists "select_propria_loja_ou_recem_criada" on public.lojas;
create policy "select_propria_loja_ou_recem_criada" on public.lojas
for select to authenticated
using (
  (id = minha_loja_id())
  or sou_admin()
  or (not exists (select 1 from perfis where perfis.loja_id = lojas.id))
);

drop policy if exists "update_propria_loja" on public.lojas;
create policy "update_propria_loja" on public.lojas
for update to authenticated
using (
  sou_admin()
  or exists (
    select 1 from loja_membros
    where loja_membros.loja_id = lojas.id
      and loja_membros.user_id = auth.uid()
      and loja_membros.role = 'owner'
  )
);

-- perfis
drop policy if exists "Usuário cria o próprio perfil no cadastro" on public.perfis;
create policy "Usuário cria o próprio perfil no cadastro" on public.perfis
for insert
with check (
  (id = auth.uid())
  and (
    sou_admin()
    or (role = 'owner'::text and not loja_tem_perfil(loja_id))
    or exists (
      select 1 from convites_usuario c
      where c.loja_id = perfis.loja_id
        and c.role = perfis.role
        and lower(trim(c.email)) = lower(trim(auth.jwt() ->> 'email'::text))
        and c.usado = true
    )
  )
);

