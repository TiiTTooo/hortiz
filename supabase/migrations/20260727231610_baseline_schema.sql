create or replace function public.assinaturas_das_minhas_lojas()
 returns table(loja_id bigint, nome text, logo text, status text, proxima_cobranca date, valor_mensal numeric, vinculada_loja_id bigint)
 language sql
 security definer
 set search_path to 'public'
as $function$
  select l.id, l.nome, l.logo,
    coalesce(a.status, 'sem_assinatura') as status,
    a.proxima_cobranca,
    coalesce(a.valor_mensal, 250) as valor_mensal,
    a.vinculada_loja_id
  from lojas l
  join loja_membros lm on lm.loja_id = l.id and lm.user_id = auth.uid() and lm.role = 'owner'
  left join assinaturas a on a.loja_id = l.id
  where coalesce(l.ativa, true) = true
  order by l.nome;
$function$;

create or replace function public.convidar_ou_vincular_comprador(p_email text, p_loja_id bigint)
 returns text
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_user_id uuid;
  v_role text;
begin
  if not exists (
    select 1 from loja_membros
    where user_id = auth.uid() and role = 'owner' and loja_id = p_loja_id
  ) and not sou_admin() then
    raise exception 'Você não tem permissão para convidar comprador pra essa loja';
  end if;

  select id into v_user_id from auth.users where lower(email) = lower(p_email) limit 1;

  if v_user_id is not null then
    select role into v_role from perfis where id = v_user_id;
    if v_role is distinct from 'comprador' then
      raise exception 'Esse e-mail já tem uma conta com outro tipo de acesso (%). Use outro e-mail para o comprador.', coalesce(v_role, 'desconhecido');
    end if;
    insert into loja_membros (user_id, loja_id, role)
    values (v_user_id, p_loja_id, 'comprador')
    on conflict (user_id, loja_id) do nothing;
    return 'vinculado';
  else
    insert into convites_usuario (email, loja_id, role, criado_por)
    values (lower(p_email), p_loja_id, 'comprador', auth.uid())
    on conflict (email, loja_id) do nothing;
    return 'convite_criado';
  end if;
end;
$function$;

