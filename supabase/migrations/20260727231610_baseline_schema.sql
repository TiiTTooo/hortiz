-- ============================================================
-- FUNÇÕES HELPER (usadas dentro das policies — precisam existir primeiro)
-- ============================================================

create or replace function public.sou_admin()
 returns boolean
 language sql
 stable security definer
 set search_path to 'public'
as $function$
  select coalesce(is_admin, false) from perfis where id = auth.uid();
$function$;

create or replace function public.minha_loja_id()
 returns bigint
 language sql
 stable security definer
 set search_path to 'public'
as $function$
  select loja_id from perfis where id = auth.uid();
$function$;

create or replace function public.loja_tem_perfil(p_loja_id bigint)
 returns boolean
 language sql
 stable security definer
 set search_path to 'public'
as $function$
  select exists (select 1 from perfis where loja_id = p_loja_id);
$function$;

