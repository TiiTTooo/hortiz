-- Baseline de schema — 2026-07-27
--
-- Este projeto nunca teve pasta supabase/migrations/: todo o schema (tabelas,
-- funções, policies de RLS, triggers, índices) foi criado direto em produção,
-- sem versionamento no git. Esta migration reconstrói o estado atual do banco
-- por introspecção (information_schema, pg_policies, pg_get_functiondef,
-- pg_indexes) — não é um `pg_dump`/`supabase db pull` real, então pode não
-- ser byte-a-byte idêntica ao histórico original de comandos, mas reflete
-- fielmente a estrutura como ela existe hoje.
--
-- É seguro rodar mais de uma vez (tudo usa IF NOT EXISTS / OR REPLACE /
-- DROP...IF EXISTS antes de recriar), porque quando isso foi aplicado pela
-- primeira vez as tabelas já existiam — o objetivo não era recriar nada, era
-- só passar a existir localmente e ficar registrado no histórico de
-- migrations do Supabase, pra que a partir de agora toda mudança de schema
-- (nova coluna, nova policy, etc.) vire uma migration nova em vez de SQL solto
-- direto em produção.
--
-- Atenção: o histórico remoto (supabase_migrations.schema_migrations) já
-- tinha 3 migrations aplicadas ANTES desta baseline, que nunca tinham
-- arquivo local correspondente:
--   20260722232214 50_restringe_update_lojas_a_owner
--   20260723005539 status_assinatura_efetiva_cobre_rede_do_dono
--   20260723172552 51_corrige_recursao_insert_nova_loja
-- O efeito das três já está refletido nesta baseline (policy "update_propria_loja"
-- e "insert_nova_loja" de lojas, e a função status_assinatura_efetiva, já
-- estão na versão corrigida). Não foram recriadas como arquivos separados
-- porque não temos o estado "antes" delas salvo em lugar nenhum — só o
-- resultado final. Se um dia alguém rodar `supabase db pull` com acesso
-- autenticado ao projeto, pode aparecer um aviso de divergência por causa
-- dessas 3 — é esperado, não é bug desta baseline.

