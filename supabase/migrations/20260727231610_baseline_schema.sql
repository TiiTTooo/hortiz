create or replace function public.excluir_loja_definitivamente(p_loja_id bigint)
 returns void
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  r record;
  fallback_loja_id bigint;
begin
  if not sou_admin() then
    raise exception 'Apenas o admin master pode excluir uma loja definitivamente';
  end if;

  -- Reatribui qualquer perfil que esteja com essa loja como ativa
  -- pra outra loja que a mesma pessoa também é dona, se existir
  for r in select id from perfis where loja_id = p_loja_id loop
    select lm.loja_id into fallback_loja_id
    from loja_membros lm
    where lm.user_id = r.id and lm.loja_id != p_loja_id
    order by lm.loja_id
    limit 1;

    if fallback_loja_id is not null then
      update perfis set loja_id = fallback_loja_id where id = r.id;
    else
      raise exception 'Não é possível excluir: o perfil % ficaria sem nenhuma loja. Vincule esse usuário a outra loja antes de excluir esta.', r.id;
    end if;
  end loop;

  delete from itens_pedido where loja_id = p_loja_id;
  delete from compras where loja_id = p_loja_id;
  delete from despesas where loja_id = p_loja_id;
  delete from margens_custom where loja_id = p_loja_id;
  delete from fornecedores where loja_id = p_loja_id;
  delete from produtos where loja_id = p_loja_id;
  delete from despesas_tipos where loja_id = p_loja_id;
  delete from "cobranças" where loja_id = p_loja_id;
  delete from assinaturas where loja_id = p_loja_id;
  delete from convites_usuario where loja_id = p_loja_id;
  delete from loja_membros where loja_id = p_loja_id;
  delete from lojas where id = p_loja_id;
end;
$function$;

create or replace function public.status_assinatura_efetiva(p_loja_id bigint)
 returns table(status text, trial_fim date, proxima_cobranca date, valor_mensal numeric, plano text)
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_sub record;
  v_melhor record;
begin
  -- só deixa consultar se quem está chamando tem alguma relação real com essa loja
  if not (
    exists(select 1 from loja_membros where user_id = auth.uid() and loja_membros.loja_id = p_loja_id)
    or exists(select 1 from perfis where id = auth.uid() and perfis.loja_id = p_loja_id)
    or sou_admin()
  ) then
    raise exception 'Sem permissão pra ver a assinatura dessa loja';
  end if;

  select * into v_sub from assinaturas where loja_id = p_loja_id;

  -- compatibilidade com o encadeamento manual já existente (isenta + vinculada_loja_id)
  if v_sub.status = 'isenta' and v_sub.vinculada_loja_id is not null then
    select * into v_sub from assinaturas where loja_id = v_sub.vinculada_loja_id;
  end if;

  -- se a própria loja (ou a loja vinculada manualmente) já está ativa/isenta, não
  -- precisa olhar a rede — devolve direto
  if v_sub.status in ('ativa','isenta') then
    return query select v_sub.status, v_sub.trial_fim, v_sub.proxima_cobranca, v_sub.valor_mensal, v_sub.plano;
    return;
  end if;

  -- rede: se QUALQUER outra loja onde o(s) mesmo(s) dono(s) desta loja também é
  -- owner estiver ativa/isenta, essa loja também fica liberada — sem precisar
  -- configurar vinculada_loja_id manualmente toda vez que uma loja nova entra
  -- na rede.
  select a.* into v_melhor
  from assinaturas a
  where a.loja_id in (
    select lm2.loja_id
    from loja_membros lm1
    join loja_membros lm2 on lm2.user_id = lm1.user_id and lm2.role = 'owner'
    where lm1.loja_id = p_loja_id and lm1.role = 'owner'
  )
  and a.status in ('ativa','isenta')
  order by (a.status = 'ativa') desc, a.proxima_cobranca desc nulls last
  limit 1;

  if v_melhor.status is not null then
    return query select v_melhor.status, v_melhor.trial_fim, v_melhor.proxima_cobranca, v_melhor.valor_mensal, v_melhor.plano;
    return;
  end if;

  -- ninguém da rede está pago — devolve o status real da própria loja (trial/vencida)
  return query select v_sub.status, v_sub.trial_fim, v_sub.proxima_cobranca, v_sub.valor_mensal, v_sub.plano;
end;
$function$;

